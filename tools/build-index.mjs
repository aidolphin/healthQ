#!/usr/bin/env node
// tools/build-index.mjs
//
// Generates the two files the app actually loads at runtime:
//
//   data/search.js  - compact catalogue, loaded eagerly. Name, category, the
//                    macros the list and totals need, and search aliases.
//   data/detail.js  - the full per-food nutrient maps, loaded LAZILY, only when
//                    someone expands "All nutrients" on a food.
//
// Why this exists
// The source files total 23 MB of JavaScript. Importing them all on the main
// thread cost ~626 ms and ~440 MB of heap, which crashes a phone before the
// first paint. The nutrient maps alone are 75% of that and are used by exactly
// one collapsed <details> panel.
//
// Run after any change to the data/ sources:
//     node tools/build-index.mjs

import { writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const p = (r) => join(ROOT, r);

const { foods, displayFoods, catalogue, groupCategory } = await import(p('data/index.js'));

// ── id remap ────────────────────────────────────────────────────────────────
// When two records shared a name, one row won and the other was folded in. A
// day-log entry saved before that merge still points at the loser's id, so we
// emit a small id -> id table and the app follows it before looking a food up.
const idRemap = {};
const seen = new Set();
for (const f of foods) {
  const k = f.name.toLowerCase().trim();
  if (seen.has(k)) idRemap[f.id] = k; // resolved to the survivor below
  else seen.add(k);
}
const survivor = new Map();
for (const f of displayFoods) survivor.set(f.name.toLowerCase().trim(), f.id);
const remap = {};
let remapCount = 0;
for (const [from, key] of Object.entries(idRemap)) {
  const to = survivor.get(key);
  if (to != null && to !== Number(from)) { remap[from] = to; remapCount++; }
}

// ── search.js ───────────────────────────────────────────────────────────────
// Short keys. This file is on the critical path, so every byte is paid for by
// every visitor on every cold load.
const rows = displayFoods.map(f => {
  const o = { i: f.id, n: f.name, c: f.category, e: f.energy };
  if (f.nepali) o.np = f.nepali;
  if (f.protein != null) o.p = f.protein;
  if (f.carbs != null) o.cb = f.carbs;
  if (f.fat != null) o.f = f.fat;
  if (f.fiber != null) o.fi = f.fiber;
  if (f.sugar != null) o.sg = f.sugar;
  if (f.water != null) o.w = f.water;
  // sodium drives a coach rule, so it stays on the eager path
  if (f.nutrients && f.nutrients['1093'] != null) o.na = f.nutrients['1093'];
  if (f.fdcId != null) o.src = f.fdcId;
  if (f.aliases && f.aliases.length) o.a = f.aliases;
  if (f.extra) o.x = f.extra;
  if (f.scientific) o.sci = f.scientific;
  return o;
});


// The sources mix date formats ("2019-04-01" and "10/30/2020") plus bare years
// derived from a source string, so slice(0,4) would emit junk like "10/2".
// Parse properly and keep only real years.
const years = (() => {
  const set = new Set();
  for (const f of displayFoods) {
    const raw = f.updated;
    if (!raw) continue;
    const asStr = String(raw).trim();
    if (/^\d{4}$/.test(asStr)) { set.add(Number(asStr)); continue; }
    const t = Date.parse(asStr);
    if (Number.isFinite(t)) {
      const d = new Date(t);
      if (d.getFullYear() > 1980 && d.getFullYear() < 2100) set.add(d.getFullYear());
    }
  }
  return [...set].sort((a, b) => a - b);
})();

const searchBody =
  `// GENERATED by tools/build-index.mjs - do not edit by hand.\n` +
  `// Compact catalogue. Loaded eagerly; keep it small.\n` +
  `export const rows=${JSON.stringify(rows)};\n` +
  `export const remap=${JSON.stringify(remap)};\n` +
  `export const meta=${JSON.stringify({ total: catalogue.unique, indexed: catalogue.total, groups: catalogue.groups, sources: catalogue.sources, years })};\n`;

writeFileSync(p('data/search.js'), searchBody);

// ── detail.js ───────────────────────────────────────────────────────────────
// Keyed by food id, loaded on demand.
const detail = {};
for (const f of displayFoods) {
  const keys = Object.keys(f.nutrients);
  if (keys.length) detail[f.id] = f.nutrients;
}
const detailBody =
  `// GENERATED by tools/build-index.mjs - do not edit by hand.\n` +
  `// Full nutrient maps, keyed by food id. Loaded lazily via dynamic import().\n` +
  `export const detail=${JSON.stringify(detail)};\n`;

writeFileSync(p('data/detail.js'), detailBody);

const kb = f => (statSync(p(f)).size / 1024).toFixed(0);
console.log('built data/search.js  ', kb('data/search.js'), 'KB  (' + rows.length.toLocaleString() + ' foods)');
console.log('built data/detail.js  ', kb('data/detail.js'), 'KB  (lazy)');
console.log('id remap entries      ', remapCount.toLocaleString());
console.log('saving vs 23 MB eager:',
  (100 - (statSync(p('data/search.js')).size / (23 * 1024 * 1024)) * 100).toFixed(1) + '% smaller on the critical path');
